// Generates src/data/dialCodes.ts: ISO alpha-2 -> international dial code for
// the countries listed in src/data/countries.ts.
// Source: mledoze/countries (countries.json, `idd` field), ODbL-1.0.
// Run: node scripts/gen-dial-codes.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE =
  "https://raw.githubusercontent.com/mledoze/countries/master/countries.json";
const OUT = new URL("../src/data/dialCodes.ts", import.meta.url);
const COUNTRIES = new URL("../src/data/countries.ts", import.meta.url);

// Countries whose idd has several suffixes that are not area codes.
const OVERRIDES = { VA: "+39", KZ: "+7", RU: "+7", EH: "+212", SH: "+290" };

const codes = [
  ...readFileSync(COUNTRIES, "utf8").matchAll(/code: "([A-Z]{2})"/g),
].map((m) => m[1]);

const data = await (await fetch(SOURCE)).json();
const idd = new Map(data.map((c) => [c.cca2, c.idd]));

const out = {};
for (const code of codes) {
  if (OVERRIDES[code]) {
    out[code] = OVERRIDES[code];
    continue;
  }
  const entry = idd.get(code);
  if (!entry?.root) continue; // no dial code (e.g. Antarctica)
  if (entry.root === "+1") out[code] = "+1"; // NANP: suffixes are area codes
  else if (entry.suffixes.length === 1) out[code] = entry.root + entry.suffixes[0];
  else console.warn(`No single dial code for ${code}:`, entry);
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${k}: "${v}",`)
  .join("\n");
writeFileSync(
  OUT,
  `// Generated by scripts/gen-dial-codes.mjs. Do not edit by hand.
// Source: mledoze/countries (https://github.com/mledoze/countries), ODbL-1.0.
export const dialCodes: Record<string, string> = {
${body}
};
`
);
console.log(`dialCodes.ts: ${Object.keys(out).length} of ${codes.length} countries`);
